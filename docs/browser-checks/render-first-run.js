/**
 * Render every first-run state in a real browser and look at it.
 *
 * ⚠️ The API responses are intercepted, NOT the render functions. The whole
 * client path -- fetch, parse, paint -- runs exactly as it does live; the only
 * thing substituted is what the server said. Calling the paint functions
 * directly would skip the part that has broken before.
 */
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');

const BASE = 'http://127.0.0.1:4399';
const OUT = process.argv[2] || '/tmp/frshots';
const HEADED = process.env.HEADED !== '0';
fs.mkdirSync(OUT, { recursive: true });

/**
 * ⚠️ NO SHOT DEPENDS ON THE MACHINE THAT RENDERS IT, and no fixture is
 * TYPED. History, because the rule inverted once in each direction: a
 * hand-written all-clear fixture went stale against corrected engine copy
 * (so fixtures must be ENGINE-GENERATED, never typed); then the live-route
 * clear shot became unsatisfiable on any machine without Kosmos.app, and
 * live-route shots were drifting per machine (a create-path machine would
 * re-shoot the adopt pictures as create). The standing rule is both
 * halves: every payload a shot depends on is pinned, and every pinned
 * payload is generated by the real engine with a control asserting the
 * state it claims.
 *
 * A machine that is fine cannot be asked to demonstrate a finding, so the mixed
 * case still needs one -- but it is GENERATED BY THE ENGINE rather than typed
 * out here. `require` resolves from this script's own directory, so the real
 * module is two levels up, and the words on the screenshot are then the words
 * the product actually emits, by construction rather than by anyone remembering
 * to update two files at once.
 */
const machineEngine = require('../../engine/machine');

/**
 * A laptop that sleeps on battery, and a launchctl that will not answer: one
 * real finding and one thing we could not check, which is the pair the counting
 * sentence exists to keep apart.
 */
const LAPTOP_PMSET = [
  'Battery Power:', ' lidwake              1', ' sleep                10', ' disksleep            10', '',
  'AC Power:', ' lidwake              1', ' sleep                0', ' disksleep            10', '',
].join('\n');

/* App-location fixtures for the return step (step 6) and the machine payloads, each GENERATED
   by the real engine against a scratch pair of folders rather than
   hand-written, so the wording on the shots cannot drift from the engine's
   (the same anti-drift property the MIXED fixture has, one step removed).
   The dirs are built once and removed at exit. */
const APPFIX = (() => {
  const os = require('node:os');
  const withApp = fs.mkdtempSync(path.join(os.tmpdir(), 'frshot-app-'));
  fs.mkdirSync(path.join(withApp, 'Kosmos.app'));
  const empty = fs.mkdtempSync(path.join(os.tmpdir(), 'frshot-empty-'));
  const sealed = fs.mkdtempSync(path.join(os.tmpdir(), 'frshot-sealed-'));
  fs.chmodSync(sealed, 0o000);
  process.on('exit', () => {
    try { fs.chmodSync(sealed, 0o755); } catch { /* gone */ }
    for (const d of [withApp, empty, sealed]) {
      try { fs.rmSync(d, { recursive: true, force: true }); } catch { /* gone */ }
    }
  });
  return {
    sys: [withApp, empty],
    home: [empty, withApp],
    none: [empty, empty],
    blind: [path.join(sealed, 'Applications'), empty],
  };
})();

const CLEAR_INPUTS = {
  pmset: ['AC Power:', ' lidwake              1', ' sleep                0', ' disksleep            10', ''].join('\n'),
  claudeBin: '/bin/sh',
  tmuxBin: '/bin/sh',
  runner: () => ({ ok: true, stdout: 'com.kosmos.agent.x' }),
};

/* The clear payload is engine-generated. (History: it was captured against
   the live route until app-location briefly joined the rows and made dev
   machines unable to read clear; app-location now rides BESIDE the rows and
   never joins the counts, but the fixture stays engine-generated -- a
   deterministic payload plus the on-screen control below is strictly
   stronger than trusting whatever machine runs the harness.) */
const MACHINE_CLEAR = (() => {
  const got = machineEngine.check({ ...CLEAR_INPUTS, appDirs: APPFIX.sys });
  if (got.attention !== 0 || got.unknown !== 0) {
    throw new Error(`the clear fixture is not clear (attention=${got.attention}, unknown=${got.unknown})`);
  }
  return got;
})();

const appFixture = (dirs, wantState, label) => {
  // (Root note: mode-000 does not seal for root, so the blind fixture reads
  // attention instead of unknown under sudo -- the throw below is loud but
  // the cause is the runner's uid, not the engine.)
  const got = machineEngine.check({ ...CLEAR_INPUTS, appDirs: dirs });
  // Its own field now, never one of `checks`: folded into the rows, step 2
  // counted it and step 4 captioned it as a reason an agent may not run.
  const row = got.appLocation;
  if (!row || row.state !== wantState) {
    throw new Error(`the ${label} app fixture reads ${row && row.state}, wanted ${wantState}`);
  }
  return got;
};
const MACHINE_APP_SYS = appFixture(APPFIX.sys, 'ok', 'system');
const MACHINE_APP_HOME = appFixture(APPFIX.home, 'ok', 'home');
const MACHINE_APP_NONE = appFixture(APPFIX.none, 'attention', 'missing');
const MACHINE_APP_BLIND = appFixture(APPFIX.blind, 'unknown', 'blind');

const MACHINE_MIXED = (() => {
  const got = machineEngine.check({
    pmset: LAPTOP_PMSET,
    claudeBin: '/bin/sh',
    tmuxBin: '/bin/sh',
    runner: (cmd) => (cmd === '/bin/launchctl' ? { ok: false, because: 'no' } : { ok: true, stdout: '' }),
    // Pinned so the appLocation field (now beside the rows, not among
    // them) stays deterministic; the counts below never included it.
    appDirs: APPFIX.sys,
  });
  // The control: this fixture is only worth screenshotting if it really does
  // carry one of each, which is the whole point of the shot.
  if (got.attention !== 1 || got.unknown !== 1) {
    throw new Error(`the mixed fixture no longer shows one of each (attention=${got.attention}, unknown=${got.unknown})`);
  }
  return got;
})();

